//! One artifact plan drives generation and read-only drift checks.

use std::path::{Path, PathBuf};

use crate::{
    Contract, binding_paths, emit_host_trait, emit_rust, emit_sdk_bindings, emit_text,
    emitted_paths,
};

/// One derived file and its complete contents.
pub struct Artifact {
    /// Destination resolved against the source contract's directory.
    pub path: PathBuf,
    /// Deterministic UTF-8 content with LF line endings.
    pub contents: String,
}

/// Why generation or checking failed.
#[derive(Debug, thiserror::Error)]
pub enum GenerateError {
    /// A source or existing artifact cannot be read.
    #[error("{}: {source}", path.display())]
    Read {
        /// The unreadable file.
        path: PathBuf,
        /// The underlying failure.
        source: std::io::Error,
    },
    /// The source contract is invalid.
    #[error(transparent)]
    Parse(#[from] crate::ParseError),
    /// The table cannot be rendered.
    #[error(transparent)]
    Render(#[from] crate::RenderError),
    /// A binding cannot represent the contract.
    #[error(transparent)]
    Binding(#[from] crate::BindingError),
    /// Check mode found missing or stale artifacts and has not changed them.
    #[error("generated WIT artifacts are stale: {paths:?}; run wit-codegen")]
    Drift {
        /// Every missing or stale destination.
        paths: Vec<PathBuf>,
    },
    /// A generated file cannot be written.
    #[error("{}: {source}", path.display())]
    Write {
        /// The unwritable destination.
        path: PathBuf,
        /// The underlying failure.
        source: std::io::Error,
    },
}

/// Plans all outputs before making filesystem changes.
///
/// # Errors
/// Rejects an invalid contract or one a binding emitter cannot represent.
pub fn artifacts(contract_path: &Path, source: &str) -> Result<Vec<Artifact>, GenerateError> {
    let source = source.replace("\r\n", "\n");
    let contract = Contract::parse(&source)?;
    let dir = contract_path.parent().unwrap_or_else(|| Path::new("."));
    let [table, report] = emitted_paths();
    let [host, _, sdk] = binding_paths();
    let bundled = |consumer: &str| {
        format!(
            "// Generated by wit-codegen from wit/synra-plugin.wit. Do not edit.\n\
         // This copy lets {consumer} without the source repository.\n\n{}\n",
            source.trim_end()
        )
    };
    Ok([
        (table, emit_rust(&contract)?),
        (report, emit_text(&contract)),
        (host, emit_host_trait(&contract)?),
        (sdk, emit_sdk_bindings(&contract)?),
        (
            "../crates/synra-plugin-sdk/wit/synra-plugin.wit",
            bundled("the SDK compile"),
        ),
        (
            "../tools/synra-plugin-cli/wit/synra-plugin.wit",
            bundled("the author CLI verify"),
        ),
    ]
    .into_iter()
    .map(|(path, contents)| Artifact {
        path: dir.join(path),
        contents,
    })
    .collect())
}

/// Generates all outputs, or checks all of them without writing.
///
/// # Errors
/// Reports input/render failures, every stale output, or an IO failure.
pub fn synchronize(contract_path: &Path, check: bool) -> Result<Vec<PathBuf>, GenerateError> {
    let source = std::fs::read_to_string(contract_path).map_err(|source| GenerateError::Read {
        path: contract_path.to_path_buf(),
        source,
    })?;
    let artifacts = artifacts(contract_path, &source)?;
    let mut changed = Vec::new();
    for artifact in &artifacts {
        match std::fs::read_to_string(&artifact.path) {
            Ok(current) if current.replace("\r\n", "\n") == artifact.contents => {}
            Ok(_) => changed.push(artifact),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => changed.push(artifact),
            Err(source) => {
                return Err(GenerateError::Read {
                    path: artifact.path.clone(),
                    source,
                });
            }
        }
    }
    if check && !changed.is_empty() {
        return Err(GenerateError::Drift {
            paths: changed
                .iter()
                .map(|artifact| artifact.path.clone())
                .collect(),
        });
    }
    for artifact in changed {
        if let Some(parent) = artifact.path.parent() {
            std::fs::create_dir_all(parent).map_err(|source| GenerateError::Write {
                path: parent.to_path_buf(),
                source,
            })?;
        }
        std::fs::write(&artifact.path, &artifact.contents).map_err(|source| {
            GenerateError::Write {
                path: artifact.path.clone(),
                source,
            }
        })?;
    }
    Ok(artifacts
        .into_iter()
        .map(|artifact| artifact.path)
        .collect())
}

