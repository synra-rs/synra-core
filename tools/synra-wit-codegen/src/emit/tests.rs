use super::*;

/// The real contract, so the tests assert against what the repository ships.
const REAL: &str = include_str!("../../wit/synra-plugin.wit");

fn contract() -> Contract {
    Contract::parse(REAL).expect("the repository's contract parses")
}

// ── The contract itself ───────────────────────────────────────────────────────────────────────

#[test]
fn the_repositorys_contract_parses_and_every_function_has_a_gate() {
    // ★ The check that matters, run against the file that ships. A function with no gate would be refused by the
    // parser, so this test passing is the statement that nothing is reachable without a capability.
    let contract = contract();
    let host = contract.host().expect("a host interface");
    assert!(!host.functions.is_empty());
    // And every function has one, which the parser guarantees — asserted here so that a future change to the parser
    // that made the gate optional fails this test rather than shipping.
    for function in &host.functions {
        assert!(
            function.gate.is_ungated() || function.gate.capability().is_some(),
            "{} has no gate",
            function.name
        );
    }
}

#[test]
fn only_the_environment_queries_are_ungated() {
    // ★ The design document's exception, asserted against the real file. Every entry here is a host call any plugin
    // may make, so the list is short and each one reads a fact rather than doing anything.
    let contract = contract();
    let ungated: Vec<&str> = contract
        .ungated()
        .iter()
        .map(|function| function.name.as_str())
        .collect();

    for name in &ungated {
        assert!(
            name.starts_with("env-")
                || *name == "platform-capabilities"
                || *name == "plugin-id",
            "{name} is ungated and is not a read-only fact"
        );
    }
    assert!(ungated.contains(&"env-sdk-version"), "{ungated:?}");
    assert!(ungated.contains(&"env-can"), "{ungated:?}");
    assert!(!ungated.contains(&"log"), "log is ungated: {ungated:?}");
    assert!(!ungated.contains(&"platform-simulate-keys"), "{ungated:?}");
}

#[test]
fn the_dangerous_capabilities_are_each_their_own() {
    // A plugin that notifies has no business simulating keystrokes, and one capability for both would make the
    // permission dialog ask for both.
    let capabilities = contract().capabilities();
    for capability in [
        "platform:notify",
        "platform:simulate-keys",
        "platform:read-clipboard",
        "platform:write-clipboard",
        "storage:local:read",
        "storage:local:write",
        "storage:secure:read",
        "storage:secure:write",
    ] {
        assert!(
            capabilities.iter().any(|known| known == capability),
            "{capability} is missing"
        );
    }
}

#[test]
fn the_host_and_its_exports_are_what_the_world_says() {
    let contract = contract();
    assert_eq!(contract.host().map(|host| host.name.as_str()), Some("host"));
    let exports: Vec<&str> = contract
        .exports()
        .iter()
        .map(|interface| interface.name.as_str())
        .collect();
    for expected in ["lifecycle", "share", "actions"] {
        assert!(
            exports.contains(&expected),
            "{expected} is not exported: {exports:?}"
        );
    }
}

#[test]
fn the_capability_list_is_sorted_and_has_no_duplicates() {
    // The list a manifest is validated against and a permission dialog shows, so a duplicate would be a dialog
    // asking twice for the same thing.
    let capabilities = contract().capabilities();
    let mut sorted = capabilities.clone();
    sorted.sort();
    sorted.dedup();
    assert_eq!(capabilities, sorted, "unsorted or duplicated");
    assert!(
        capabilities.len() > 15,
        "only {} capabilities",
        capabilities.len()
    );
}

// ── The Rust output ───────────────────────────────────────────────────────────────────────────

#[test]
fn the_rust_output_is_sorted_and_carries_the_header() {
    let rust = emit_rust(&contract()).expect("renders");
    assert!(rust.starts_with("// Generated by `synra-wit-codegen`"), "{rust}");
    assert!(rust.contains("pub const HOST_FUNCTIONS"), "{rust}");

    // Sorted by import name, so a binary search and a stable diff are the same decision.
    let names: Vec<&str> = rust
        .lines()
        .filter_map(|line| line.trim().strip_prefix("(\""))
        .filter_map(|line| line.split('"').next())
        .collect();
    let mut sorted = names.clone();
    sorted.sort_unstable();
    assert_eq!(names, sorted, "the table is not sorted");
}

#[test]
fn an_ungated_function_is_rendered_as_none() {
    // So the host's lookup has one shape to match on: a capability, or nothing.
    let rust = emit_rust(&contract()).expect("renders");
    assert!(
        rust.contains("(\"synra:plugin/host#env-sdk-version\", None)"),
        "{rust}"
    );
    assert!(
        rust.contains("(\"synra:plugin/host#log\", Some(\"log:*\"))"),
        "{rust}"
    );
}

#[test]
fn a_contract_with_no_host_is_refused_rather_than_rendered_empty() {
    // An empty table would be a host that answers no call and a generated file that says nothing is wrong.
    let contract = Contract::parse(
        "package synra:plugin@1.0.0;\ninterface lifecycle {\n    activate: func();\n}\nworld plugin { export lifecycle; }\n",
    )
    .expect("parses");
    assert_eq!(emit_rust(&contract), Err(RenderError::NoHost));
}

#[test]
fn the_rust_output_round_trips_through_the_parser_it_was_made_for() {
    // Every name the table carries is a name in the contract, and every capability is one of the contract's. A
    // generator that invented either would produce a host checking a capability no manifest can declare.
    let contract = contract();
    let rust = emit_rust(&contract).expect("renders");

    for (name, gate) in contract.capability_table() {
        assert!(rust.contains(&name), "{name} is missing from the output");
        if let Some(capability) = gate.capability() {
            assert!(rust.contains(capability), "{capability} is missing");
        }
    }
}

// ── The text output ───────────────────────────────────────────────────────────────────────────

#[test]
fn the_text_output_lists_what_a_reviewer_checks() {
    let text = emit_text(&contract());
    assert!(text.contains("ungated:"), "{text}");
    assert!(text.contains("gated:"), "{text}");
    assert!(text.contains("capabilities:"), "{text}");
    // Every ungated function is named under `ungated`, which is the list a reviewer reads first.
    for function in contract().ungated() {
        let ungated_section = text.split("\ngated:").next().unwrap_or_default();
        assert!(
            ungated_section.contains(&function.name),
            "{} is not listed",
            function.name
        );
    }
}

#[test]
fn the_text_output_uses_the_bare_function_name_in_the_table() {
    // The package prefix is the same on every line, so a reader checking the mapping does not need it three times
    // per row.
    let text = emit_text(&contract());
    let gated = text.split("\ngated:").nth(1).expect("a gated section");

    // The section starts at the line `gated:` and not at the `gated` inside `ungated`, which is what a split on
    // the bare word found.
    assert!(gated.contains("log: log:*"), "{gated}");
    assert!(!gated.contains("synra:plugin/host#log"), "{gated}");
}

// ── The paths ─────────────────────────────────────────────────────────────────────────────────

#[test]
fn the_emitted_paths_are_where_the_generated_files_live() {
    // Asserted so the CI check and the writer cannot disagree about where the files go — a disagreement whose
    // symptom is a check that always passes.
    let [rust, text] = emitted_paths();
    assert!(rust.ends_with("capability_table.rs"), "{rust}");
    // Relative to the contract's directory, which is `wit/`: the host crate is its sibling's child, and the text
    // report sits beside the contract.
    assert!(rust.starts_with("../crates/synra-plugin-host/"), "{rust}");
    assert_eq!(text, "GENERATED.md");
}

#[test]
fn render_errors_explain_themselves() {
    let text = RenderError::NoHost.to_string();
    assert!(text.len() > 30, "{text}");
    assert!(!text.contains('{'), "{text}");
}
