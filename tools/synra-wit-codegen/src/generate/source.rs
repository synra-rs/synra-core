//! Assembles the workspace contract from its maintained interfaces.

use std::path::Path;

use super::GenerateError;

/// Inputs beside the generated workspace contract, in package order.
pub const WORKSPACE_FRAGMENTS: [&str; 3] =
    ["source/types.wit", "source/host.wit", "source/guest.wit"];

/// Reads the workspace fragments when the contract has a source directory.
///
/// Standalone contracts, including published crate resources, are read by their callers as single files.
///
/// # Errors
/// Reports an inaccessible source directory or an unreadable fragment.
pub fn workspace_source(contract_path: &Path) -> Result<Option<String>, GenerateError> {
    let Some(directory) = contract_path.parent() else {
        return Ok(None);
    };
    if !contract_path.ends_with("synra-plugin.wit") {
        return Ok(None);
    }
    let source_directory = directory.join("source");
    if !source_directory.try_exists().map_err(|source| GenerateError::Read {
        path: source_directory,
        source,
    })? {
        return Ok(None);
    }

    let mut fragments = Vec::with_capacity(WORKSPACE_FRAGMENTS.len());
    for fragment in WORKSPACE_FRAGMENTS {
        let path = directory.join(fragment);
        let contents = std::fs::read_to_string(&path).map_err(|source| GenerateError::Read {
            path,
            source,
        })?;
        fragments.push(contents.replace("\r\n", "\n"));
    }
    let sections: Vec<&str> = fragments.iter().map(|fragment| fragment.trim_end()).collect();
    Ok(Some(sections.join("\n\n")))
}

/// Renders the combined contract used by the workspace and packaged consumers.
#[must_use]
pub fn combined_wit(source: &str) -> String {
    format!(
        "// Generated by synra-wit-codegen from wit/source. Do not edit.\n\n{}\n",
        source.trim_end()
    )
}
