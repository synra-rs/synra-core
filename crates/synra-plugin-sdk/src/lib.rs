//! What a Synra plugin is written against.
//!
//! # What is here
//!
//! The **generated host bindings**: one function per host call, with the import name the component model resolves and
//! the signature the contract declares. Generated from `wit/synra-plugin.wit`, so a plugin that calls a function the
//! contract does not declare gets a compile error in its own crate rather than a trap when the kernel instantiates it.
//!
//! Public boundary types and guest traits are re-exported from the generated WIT bindings,
//! so host functions and plugin entry points use the same Rust types without a manual mirror.
//!
//! # Why this crate is thin
//!
//! It is what a plugin *links*, so everything in it is in the user's download. The generated bindings are the whole
//! surface, and the logic is the kernel's, on the other side of the boundary.
//!
//! # How the bindings are made
//!
//! `wit_bindgen::generate!` in [`generated`] reads this crate's bundled WIT at compile time. The workspace
//! generator derives that resource from the primary contract; its read-only check covers every artifact.
//! Consumers need only this crate and its declared dependencies, without the source repository beside it.

#![forbid(unsafe_code)]
#![warn(missing_docs)]
// Test code is exempt from the no-panic rules; see `synra-protocol` for the reasoning. An assertion about a generated
// signature is the shape these tests have.
#![cfg_attr(
    test,
    allow(
        clippy::unwrap_used,
        clippy::expect_used,
        clippy::panic,
        clippy::indexing_slicing,
        clippy::needless_pass_by_value,
    )
)]

pub mod generated {
    //! The generated bindings.
    //!
    //! # Generated at compile time, and not by a build step
    //!
    //! Bindings use this crate's own `wit/synra-plugin.wit` resource. In the workspace, run `synra-wit-codegen`
    //! after changing the primary contract, then `synra-wit-codegen --check` to validate all derived files.
    //! The compiler checks Rust signatures against the bundled contract.
    //!
    //! # The file beside this one is generated by a different tool
    //!
    //! `src/generated/imports.rs` is `synra-wit-codegen`'s output: the import names, one constant per host function, which a
    //! build script can read without compiling anything. `wit_bindgen` does not emit them in that form, and the suite
    //! compares the two — two generators, one contract, and a test that says they agree.
    //!
    //! The documentation `wit-bindgen` emits is derived from the WIT comments and does not cover every generated item,
    //! so the lint is off here rather than the contract being rewritten to satisfy a linter.
    #[allow(missing_docs)]
    pub mod bindings {
        wit_bindgen::generate!({
            path: "wit",
            world: "plugin",
            pub_export_macro: true,
            export_macro_name: "__export_plugin",
        });

        /// The host calls, under the path this crate has always exposed them at.
        ///
        /// `wit_bindgen` names the module after the interface — `synra::plugin::host` — and this alias is what keeps a
        /// plugin's `synra_plugin_sdk::host::log(..)` working without it having to name the package and the version.
        pub use synra::plugin::host;
    }

    pub mod imports {
        //! The import names, on their own, for a build script that wants them without compiling the module.
        include!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/src/generated/imports.rs"
        ));
    }
}

/// The host calls, re-exported at the top level.
///
/// So a plugin writes `synra_plugin_sdk::host::log(..)` rather than `synra_plugin_sdk::generated::bindings::host::log`,
/// and the path in a plugin's source names the thing it is calling rather than where the file was put.
pub use generated::bindings::host;

// Guest ABI types are generated from WIT; host-side manifest models are not linked into a guest.
/// The WIT guest traits implemented by a plugin's entry point.
pub use generated::bindings::exports;
pub use generated::bindings::synra::plugin::types::{
    DeviceKind, DeviceTarget, Error, LogLevel, Outcome,
};

/// Exports a plugin implementing the lifecycle, share and actions WIT guest traits.
///
/// Bindings are generated once in this SDK; callers never regenerate a second world or write raw exports.
#[macro_export]
macro_rules! export {
    ($plugin:ident) => {
        $crate::generated::bindings::__export_plugin!($plugin with_types_in $crate::generated::bindings);
    };
}

/// The version of the plugin contract these bindings were generated from.
///
/// A plugin states the SDK version it was built against in its manifest, and the host refuses a plugin whose `sdk.min`
/// is above what it supports. This constant is what a plugin's build script reports rather than a string somebody typed.
pub const CONTRACT_VERSION: &str = generated::imports::PACKAGE_VERSION;

/// The interface a plugin imports.
pub const HOST_INTERFACE: &str = generated::imports::HOST_INTERFACE;

/// The world a plugin implements.
pub const PLUGIN_WORLD: &str = generated::imports::PLUGIN_WORLD;

